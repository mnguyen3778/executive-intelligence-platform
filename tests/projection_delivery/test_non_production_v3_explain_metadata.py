def encode(value):
    return json.dumps(value, ensure_ascii=True, sort_keys=True,
                      separators=(",", ":"), allow_nan=False).encode()


class Reader:
    def __init__(self, current):
        self.current = current
        self.calls = 0
        self.second = None

    def __call__(self):
        self.calls += 1
        if self.calls > 1 and self.second is not None:
            return self.second
        return self.current



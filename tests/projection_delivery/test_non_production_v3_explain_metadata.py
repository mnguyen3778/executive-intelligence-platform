class MetadataSuccessTests(unittest.TestCase):
    def check_success(self, harness, count):
        result = harness.verifier.verify(encode(harness.envelope))
        self.assertIs(type(result), metadata.VerifiedSyntheticV3ExplainMetadata)
        self.assertEqual(result.limitations, tuple(TEXTS[:count]))
        self.assertEqual(result.selection["artifact_instance_id"], harness.artifact.artifact_instance_id)
        self.assertEqual(result.publication["occurrence"], "occurrence-A")
        self.assertEqual(result.publication["revision"], "revision-A")
        self.assertEqual(result.provenance["policy_revision"], PIN)
        self.assertEqual(tuple((r["field"], r["classification"]) for r in result.field_classifications),
                         tuple((r["field"], r["classification"]) for r in CLASSES))
        self.assertFalse(result.release_eligible)
        self.assertEqual([harness.pub_reader.calls, harness.c_reader.calls, harness.b_reader.calls], [2, 2, 2])
        self.assertFalse(hasattr(result, "to_dict"))
        with self.assertRaises(FrozenInstanceError):
            result.release_eligible = True
        with self.assertRaises(TypeError):
            result.selection["artifact_instance_id"] = "substitute"
        with self.assertRaises(TypeError):
            result.field_classifications[0]["classification"] = "public"
        with self.assertRaises(TypeError):
            json.dumps(result)
        return result

    def test_finding_scoped_exact_metadata(self):
        self.check_success(Harness(), 2)

    def test_no_findings_complete_conditional_caveat(self):
        self.check_success(Harness(no_findings=True), 3)

    def test_verified_inapplicable_client_workspace_are_null(self):
        self.check_success(Harness(optional_scope=True), 2)


def change(path, value):
    def mutate(envelope):
        target = envelope
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = value
    return mutate


